<div class="shell">
	<h1>Watching it without hurting your eyes</h1>
	<p class="lede">
		The Sun does not become more dangerous during an eclipse. What changes is that an eclipse gives
		people a reason to stare at it, and a partly covered Sun is comfortable enough to look at that the
		usual reflex to look away is weakened. The damage is painless and can be permanent.
	</p>

	<div class="note note-danger">
		<strong>The one rule:</strong> if any part of the Sun's bright surface is showing — even one
		percent — you need a certified solar filter over your eyes. The only exception is the couple of
		minutes of total eclipse inside the narrow path, when the Sun is completely covered.
	</div>

	<h2>What actually works</h2>
	<ul>
		<li>
			<strong>Eclipse glasses or handheld viewers certified to ISO 12312-2.</strong> These cut the
			Sun's light by a factor of about 100,000 and block infrared and ultraviolet as well as visible
			light. Through them you should see nothing at all except the Sun itself.
		</li>
		<li>
			<strong>A purpose-made solar filter</strong> fitted over the <em>front</em> of a telescope,
			binoculars or a camera lens.
		</li>
		<li>
			<strong>Welding glass of shade 14 or darker.</strong> Shade 12 and 13 are not dark enough for
			comfortable, safe viewing; the shade numbers commonly sold for arc welding (10–12) are
			definitely not.
		</li>
		<li>
			<strong>Indirect projection.</strong> Pinhole projection, a colander, a straw hat, or the gaps
			between tree leaves will all cast little crescent images of the eclipsed Sun on the ground.
			This is completely safe because you never look at the Sun at all.
		</li>
	</ul>

	<h2>What does not work, whatever you have heard</h2>
	<ul>
		<li>Sunglasses, including several pairs stacked, and including polarised ones.</li>
		<li>Smoked glass, exposed photographic film, X-ray film.</li>
		<li>CDs, DVDs, floppy disks, mylar food packaging, space blankets.</li>
		<li>Neutral-density or polarising photographic filters — these do not block infrared.</li>
		<li>
			Looking at the Sun's reflection in water, or through a phone's camera while glancing at the
			screen with your other eye open.
		</li>
		<li>
			A telescope or binoculars with a filter that screws in at the <em>eyepiece</em> end. These
			concentrate the Sun's heat onto the filter and can crack it without warning.
		</li>
	</ul>

	<h2>Using eclipse glasses properly</h2>
	<ol>
		<li>
			Check they carry the ISO 12312-2 reference and buy from a supplier you can identify. Fakes are
			common around big eclipses.
		</li>
		<li>
			Inspect them against a bright lamp before eclipse day. Discard any with scratches, pinholes,
			creases, or film separating from the frame.
		</li>
		<li>
			Put them on <em>before</em> you look up, and turn away from the Sun before taking them off.
		</li>
		<li>
			Supervise children directly — an adult per child is not excessive. Glasses slip, and children
			peek round the edges.
		</li>
		<li>
			If you wear prescription glasses, wear the eclipse glasses over them rather than instead of
			them.
		</li>
	</ol>

	<h2>Cameras, binoculars and telescopes</h2>
	<p>
		Any optic gathers far more light than your eye and concentrates it. A pair of binoculars pointed
		at the Sun without a front filter will cause serious injury essentially instantly, and will also
		destroy a camera sensor. Eclipse glasses held to the eyepiece are <em>not</em> a substitute: the
		concentrated beam can burn straight through them.
	</p>
	<p>
		The filter must go over the front aperture, be firmly attached so wind cannot dislodge it, and stay
		on for the whole partial phase. Cover any finderscope too, or remove it.
	</p>

	<h2>The exception: totality itself</h2>
	<p>
		Inside the path of totality, once the Moon covers the Sun completely, there is no bright
		photosphere left and it is safe — and necessary — to look with your naked eye. The corona is about
		as bright as a full Moon. Through a filter you will see nothing at all and will miss the entire
		event.
	</p>
	<div class="steps">
		<div class="card">
			<h3>Take the filter off</h3>
			<p>
				When the last bead of sunlight goes out and the diamond ring fades, glasses off. Not before.
				If you are unsure, wait a beat — the sky going suddenly dark is unmistakable.
			</p>
		</div>
		<div class="card">
			<h3>Watch, do not fiddle</h3>
			<p>
				In northern Spain totality lasts between about 30 and 105 seconds. That is not enough time
				to troubleshoot a camera. Look at it.
			</p>
		</div>
		<div class="card">
			<h3>Filter back on at the first light</h3>
			<p>
				The moment any point of brightness reappears on the opposite edge, look away and put the
				glasses back on. Third contact arrives faster than people expect.
			</p>
		</div>
	</div>

	<div class="note note-danger">
		<strong>If you are outside the path</strong> — including Madrid, Barcelona, Lisbon, London, Paris
		and everywhere else in Europe — there is no safe moment at all. The Sun is never completely
		covered where you are, so the filter stays on from start to finish. Check
		<a href="/where">whether your location is inside the path</a> before eclipse day, not during it.
	</div>

	<h2>Pinhole projection, in one minute</h2>
	<p>
		Punch a small clean hole in a piece of card. Stand with your back to the Sun and hold the card so
		sunlight passes through the hole onto a second piece of card a metre or so behind it. The patch of
		light is an image of the Sun, and during the eclipse it will be a crescent. A bigger separation
		gives a bigger, fainter image. Two crossed hands with fingers slightly spread work almost as well.
	</p>

	<h2>If you think you have been dazzled</h2>
	<p>
		Solar retinopathy usually shows up hours later as a blurred or blank patch in the centre of vision,
		or distorted straight lines. It does not hurt, which is exactly why it is dangerous. If you notice
		any change in your vision after looking at the Sun, contact an optometrist or an eye casualty
		service promptly rather than waiting to see whether it settles.
	</p>

	<p class="sources">
		This page follows the standard guidance from the American Astronomical Society's solar eclipse
		task force, NASA and the Royal Astronomical Society. If something you read elsewhere contradicts
		it, prefer those sources over this one.
	</p>
</div>

